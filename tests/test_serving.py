def test_server_predict_map_all_36_subdivisions():
    """Verify server.predict_map returns 36 subdivisions with valid ranges."""
    server = get_model_server()
    assert server is not None

    cmap = server.predict_map(lead_day=6, date="2002-07-16")
    assert isinstance(cmap, ConfidenceMap)
    assert cmap.lead_day == 6
    assert cmap.date == "2002-07-16"
    assert cmap.is_live is True
    assert cmap.model_version in ("pratyaya-v0.2.0-day4", "pratyaya-v1.0.0-heldout")
