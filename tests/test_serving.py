def test_api_default_date_resolves_to_cycle_date_with_variance():
    """Verify querying /api/forecast/map with NO date defaults to 2002-07-16 and has non-zero variance."""
    resp = client.get("/api/forecast/map?lead=4")
    assert resp.status_code == 200
    data = resp.json()
    assert data["date"] == "2002-07-16"
    pbusts = [r["p_bust"] for r in data["regions"]]
    assert len(pbusts) == 36
    # Must have meaningful variation across subdivisions, NOT flat/constant
    assert min(pbusts) < max(pbusts), "p_bust must not be constant across regions on default cycle date"
    assert len(set(pbusts)) > 1


def test_api_non_cycle_date_returns_400_with_nearest_dates():
    """Verify querying non-cycle dates returns 400 Bad Request with nearest valid dates rather than flat dummy data."""
    for bad_date in ["2002-07-15", "2002-07-14", "2002-08-02"]:
        resp = client.get(f"/api/forecast/map?lead=4&date={bad_date}")
        assert resp.status_code == 400, f"Expected 400 for bad date {bad_date}, got {resp.status_code}"
        err = resp.json()["detail"]
        assert "not a valid forecast initialization cycle date" in err
        assert "Nearest valid cycle dates" in err



