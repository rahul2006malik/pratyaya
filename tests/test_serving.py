    data_map = res_map.json()
    assert data_map["is_live"] is True
    assert data_map["model_version"] in ("pratyaya-v0.2.0-day4", "pratyaya-v1.0.0-heldout")
    assert len(data_map["regions"]) == 36

    # 3. Forecast Region Card
    res_card = client.get("/api/forecast/region/7?lead=6&date=2002-07-16")
    assert res_card.status_code == 200
    data_card = res_card.json()
    assert data_card["is_live"] is True
    assert len(data_card["top_analogues"]) == 8

    # 4. Forecast Queue
    res_queue = client.get("/api/forecast/queue?lead=6&date=2002-07-16&top_n=10")
