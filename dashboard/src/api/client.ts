/**
 * Typed API Client for Project Pratyaya
 * Connects directly to FastAPI (http://localhost:8000) or proxies via Vite (/api),
 * and falls back seamlessly to deterministic local mock data for 100% offline demo mode.
 */

import {
  ConfidenceMap,
  ErrorProneAreas,
  ForecastCard,
  ModelStatus,
  RegimesResponse,
  ReplayScenario,
  ScenarioSummary,
} from './types';
import {
  getMockConfidenceMap,
  getMockReviewQueue,
  getMockForecastCard,
  getMockModelStatus,
  getMockRegimes,
  getMockReplay,
  getMockReplayScenarios,
} from '../data/mock_data';

// Helper to check if demo mode is requested via URL (?demo=true) or environment
export function isDemoModeExplicit(): boolean {
  if (typeof window === 'undefined') return false;
  const params = new URLSearchParams(window.location.search);
  return params.get('demo') === 'true' || params.get('offline') === 'true';
}

const BACKEND_URL =
  typeof window !== 'undefined' &&
  (window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1')
    ? 'http://localhost:8000'
    : '';

// Helper to map API endpoint paths to pre-scored static JSON artefacts
function mapPathToStaticDataUrl(path: string): string | null {
  try {
    const url = new URL(path, 'http://localhost');
    const pathname = url.pathname;
    const params = url.searchParams;

    if (pathname === '/api/model/status') {
      return '/data/model_status.json';
    }
    const date = params.get('date');
    if (date && date !== '2002-06-07') {
      return null;
    }

    if (pathname === '/api/forecast/map' || pathname === '/api/confidence-map') {
      const lead = params.get('lead') || params.get('lead_day') || '6';
      const variable = params.get('variable') || 'rainfall';
      return variable === 't2m'
        ? `/data/confidence_map_lead_${lead}_t2m.json`
        : `/data/confidence_map_lead_${lead}.json`;
    }
    if (pathname === '/api/forecast/queue' || pathname === '/api/error-prone-areas') {
      const lead = params.get('lead');
      return lead ? `/data/review_queue_lead_${lead}.json` : '/data/review_queue.json';
    }
    const regionMatch = pathname.match(/^\/api\/forecast\/region\/([0-9]+)/);
    if (regionMatch) {
      const regId = regionMatch[1];
      const lead = params.get('lead');
      return lead === '4'
        ? `/data/forecast_region_${regId}_lead_4.json`
        : `/data/forecast_region_${regId}.json`;
    }
    if (pathname === '/api/demo/replay/scenarios') {
      return '/data/replay_scenarios.json';
    }
    if (pathname === '/api/demo/replay') {
      const scenId = params.get('scenario_id') || 'july2002_break';
      return `/data/replay_${scenId}.json`;
    }
    if (pathname === '/api/regimes') {
      return '/data/regimes.json';
    }
  } catch {
    // Malformed URL, fall through
  }
  return null;
}

export class PratyayaApiClient {
  private forceOffline: boolean = isDemoModeExplicit();
  private isConnected: boolean = false;
  private onConnectionChange?: (isLive: boolean) => void;

  constructor(onConnectionChange?: (isLive: boolean) => void) {
    this.onConnectionChange = onConnectionChange;
  }

  public setForceOffline(offline: boolean) {
    this.forceOffline = offline;
    if (this.onConnectionChange) {
      this.onConnectionChange(!offline && this.isConnected);
    }
  }

  public getIsForceOffline(): boolean {
    return this.forceOffline;
  }

  private async requestJson<T>(path: string, fallbackFn: () => T): Promise<T> {
    // 1. Tier 1: Try Live Backend API (if not explicitly forced offline)
    if (!this.forceOffline) {
      const urlsToTry = BACKEND_URL ? [`${BACKEND_URL}${path}`, path] : [path];
      for (const url of urlsToTry) {
        try {
          const res = await fetch(url, { signal: AbortSignal.timeout(2500) });
          if (res.ok) {
            const data: T = await res.json();
            this.isConnected = true;
            this.onConnectionChange?.(true);
            return data;
          }
        } catch {
          // try next candidate URL
        }
      }
    }

    // 2. Tier 2: Try Pre-scored Static Artefact (/data/*.json) generated by `make export`
    const staticUrl = mapPathToStaticDataUrl(path);
    if (staticUrl) {
      try {
        const staticRes = await fetch(staticUrl, { signal: AbortSignal.timeout(1500) });
        if (staticRes.ok) {
          const data: T = await staticRes.json();
          this.isConnected = false;
          this.onConnectionChange?.(false);
          return data;
        }
      } catch {
        // Fall through to in-memory mock
      }
    }

    // 3. Tier 3: In-memory deterministic TypeScript mock provider
    console.warn(`[Pratyaya API] Using deterministic in-memory provider for ${path}.`);
    this.isConnected = false;
    this.onConnectionChange?.(false);
    return fallbackFn();
  }

  public async checkHealth(): Promise<boolean> {
    if (this.forceOffline) {
      this.isConnected = false;
      this.onConnectionChange?.(false);
      return false;
    }
    const healthUrls = BACKEND_URL ? [`${BACKEND_URL}/health`, '/health'] : ['/health'];
    for (const url of healthUrls) {
      try {
        const res = await fetch(url, { signal: AbortSignal.timeout(1500) });
        if (res.ok) {
          this.isConnected = true;
          this.onConnectionChange?.(true);
          return true;
        }
      } catch {
        // try next
      }
    }
    this.isConnected = false;
    this.onConnectionChange?.(false);
    return false;
  }

  public async getConfidenceMap(
    lead: number = 6,
    date: string = '2002-07-16',
    variable: string = 'rainfall'
  ): Promise<ConfidenceMap> {
    return this.requestJson(
      `/api/forecast/map?lead=${lead}&date=${date}&variable=${variable}`,
      () => getMockConfidenceMap(lead, date, variable)
    );
  }

  public async getForecastRegion(
    regionId: string,
    lead: number = 6,
    date: string = '2002-07-16'
  ): Promise<ForecastCard> {
    return this.requestJson(
      `/api/forecast/region/${regionId}?lead=${lead}&date=${date}`,
      () => getMockForecastCard(regionId, lead, date)
    );
  }

  public async getReviewQueue(
    lead?: number,
    date: string = '2002-07-16',
    topN: number = 10
  ): Promise<ErrorProneAreas> {
    const leadParam = lead !== undefined ? `&lead=${lead}` : '';
    return this.requestJson(
      `/api/forecast/queue?date=${date}&top_n=${topN}${leadParam}`,
      () => getMockReviewQueue(lead, date, topN)
    );
  }

  public async getModelStatus(): Promise<ModelStatus> {
    return this.requestJson('/api/model/status', () => getMockModelStatus());
  }

  public async fetchReplay(
    scenarioId: string = 'july2002_break',
    maxLead: number = 7
  ): Promise<ReplayScenario> {
    return this.requestJson(
      `/api/demo/replay?scenario_id=${scenarioId}&max_lead=${maxLead}`,
      () => getMockReplay(scenarioId, maxLead)
    );
  }

  public async getReplayScenarios(): Promise<ScenarioSummary[]> {
    return this.requestJson('/api/demo/replay/scenarios', () => getMockReplayScenarios());
  }

  public async getRegimes(): Promise<RegimesResponse> {
    return this.requestJson('/api/regimes', () => getMockRegimes());
  }
}

export const apiClient = new PratyayaApiClient();
